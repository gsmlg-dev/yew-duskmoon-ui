#!/usr/bin/env python3
"""Refresh browser assets from integrity-pinned upstream archives/releases.

Run from any directory. The adjacent sources.json records exact upstream
versions, archive checksums and selected files. No package install scripts run.
"""

import base64
import concurrent.futures
import hashlib
import io
import json
from pathlib import Path
import subprocess
import tarfile
import tempfile
import threading
import urllib.request

from split_zsh_lexer import split_zsh_lexer


ROOT = Path(__file__).resolve().parent.parent
BUILD_LOCK = threading.Lock()


def vendor(source):
    request = urllib.request.Request(source["url"], headers={"User-Agent": "code-engine-asset-vendor"})
    with urllib.request.urlopen(request, timeout=60) as response:
        archive = response.read()
    algorithm, expected = source["integrity"].split("-", 1)
    actual = base64.b64encode(hashlib.new(algorithm, archive).digest()).decode()
    if actual != expected:
        raise ValueError(f"Archive checksum mismatch: {source['package']}@{source['version']}")
    if "asset" in source:
        return {source["asset"]: archive}
    files = {}
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as package:
        for target, members in source["files"].items():
            chunks = []
            for member in members:
                extracted = package.extractfile(member)
                if extracted is None:
                    raise ValueError(f"Missing regular file: {member}")
                chunks.append(extracted.read())
            contents = b"\n".join(chunks)
            if target in source.get("include_children", []):
                contents = contents.replace(
                    b"@injection.content",
                    b"@injection.content\n  (#set! injection.include-children)",
                )
            files[target] = contents
        if source.get("builds"):
            with tempfile.TemporaryDirectory(prefix="code-engine-grammar-") as directory:
                package.extractall(directory, filter="data")
                for target, grammar in source["builds"].items():
                    output = Path(directory) / "grammar.wasm"
                    if source.get("split_zsh_lexer"):
                        assert (source["package"], source["version"]) == ("tree-sitter-zsh", "0.63.1")
                        split_zsh_lexer(Path(directory) / grammar / "src/parser.c")
                    # The CLI initializes a shared WASI SDK cache on first use.
                    # Concurrent first builds can corrupt that SDK download.
                    with BUILD_LOCK:
                        subprocess.run(
                            ["tree-sitter", "build", "--wasm", "--output", str(output), str(Path(directory) / grammar)],
                            check=True,
                        )
                    files[target] = output.read_bytes()
    return files


def write_rust_manifest(assets, languages):
    lines = [
        "// Generated by scripts/vendor_syntax_assets.py. Do not edit by hand.",
        "/// Language modes included in the self-hosted Worker bundle.",
        "pub const BUNDLED_SYNTAX_LANGUAGES: &[&str] = &[",
        *[f'    "{language}",' for language in sorted(languages)],
        "];",
        "",
        "const ASSETS: &[(&str, &[u8])] = &[",
        *[f'    asset!("{name}"),' for name in sorted(assets)],
        "];",
        "",
    ]
    (ROOT / "src/bundled_assets.rs").write_text("\n".join(lines))


def main():
    config = json.loads((ROOT / "scripts/sources.json").read_text())
    if any(source.get("builds") for source in config["sources"]):
        for command, expected in config["toolchain"].items():
            version = subprocess.check_output([command, "--version"], text=True)
            if expected not in version:
                raise ValueError(f"Expected {command} {expected}, got {version.splitlines()[0]}")
    # Complete all downloads, integrity checks and builds before replacing assets.
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as executor:
        groups = list(executor.map(vendor, config["sources"]))
    files = {}
    for group in groups:
        if files.keys() & group.keys():
            raise ValueError(f"Duplicate asset outputs: {files.keys() & group.keys()}")
        files.update(group)
    fragments = set()
    for target, members in config["compositions"].items():
        files[target] = b"\n".join(files[member] for member in members)
        fragments.update(members)
    for fragment in fragments:
        del files[fragment]
    assets = ROOT / "assets"
    manifest = json.loads((assets / "manifest.json").read_text())
    for language, entry in manifest["languages"].items():
        if "alias" in entry:
            assert entry["alias"] in manifest["languages"], language
        else:
            for field in ["wasm", "query", "injections"]:
                if field in entry:
                    assert entry[field] in files, f"{language}: missing {entry[field]}"
    for name, contents in files.items():
        target = assets / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(contents)
    checksums = {
        name: hashlib.sha256(contents).hexdigest()
        for name, contents in sorted(files.items())
    }
    checksums["manifest.json"] = hashlib.sha256((assets / "manifest.json").read_bytes()).hexdigest()
    (assets / "SHA256SUMS.json").write_text(json.dumps(checksums, indent=2) + "\n")
    write_rust_manifest([*files, "worker.js", "manifest.json", "SHA256SUMS.json"], manifest["languages"])
    print(f"Vendored {len(checksums)} assets for {len(manifest['languages'])} language modes")


if __name__ == "__main__":
    main()
